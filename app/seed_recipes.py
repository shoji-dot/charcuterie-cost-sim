def seed(db):
    """DBにレシピが未登録の場合のみシードを実行"""
    from app.models import RecipeTemplate, TemplateIngredient
    if db.query(RecipeTemplate).count() > 0:
        return  # 既に登録済み
    for r in SEED_RECIPES:
        tmpl = RecipeTemplate(name=r["name"])
        db.add(tmpl)
        db.flush()
        for ing in r["ingredients"]:
            db.add(TemplateIngredient(
                template_id=tmpl.id,
                name=ing[0], default_amount=ing[1],
                unit=ing[2], category=ing[3],
            ))
    db.commit()
    print(f"[seed] {len(SEED_RECIPES)} レシピを登録しました")
